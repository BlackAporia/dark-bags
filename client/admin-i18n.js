const L = 'А-Яа-яІіЇїЄєҐґ’\'';
const keys = Object.keys(D).sort((a, b) => b.length - a.length);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RX = new RegExp(`(?<![${L}])(${keys.map(esc).join('|')})(?![${L}])`, 'g');

export function tr(text, lang) {
  if (lang === 'uk' || !text || !/[А-Яа-яІіЇїЄєҐґ]/.test(text)) return text;
  const i = lang === 'ru' ? 1 : 0;
  return text.replace(RX, (m) => D[m]?.[i] ?? m);
}

// translate every text node and tooltip under root
export function localize(root, lang) {
  if (lang === 'uk') return;
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    const v = tr(n.nodeValue, lang);
    if (v !== n.nodeValue) n.nodeValue = v;
  }
  for (const el of root.querySelectorAll('[title]')) el.title = tr(el.title, lang);
}
